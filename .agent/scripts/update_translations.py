def update_json(file_path):
    with open(file_path, 'r', encoding='utf-8') as f:
        data = json.load(f)

    def update_recursive(obj, prefix=''):
        keys_to_update = []
        for k, v in obj.items():
            full_key = f"{prefix}.{k}" if prefix else k
            if isinstance(v, dict):
                update_recursive(v, full_key)
            elif isinstance(v, str):
                # If we have a translation for this key (full path)
                if full_key in translations:
                    keys_to_update.append((k, translations[full_key]))
                # If we have a translation for the value (which acts as key in mirror keys often)
                elif v in translations:
                    keys_to_update.append((k, translations[v]))
                # Case where key is used directly in flat structure or mirror
                elif k in translations and v == k: 
                     keys_to_update.append((k, translations[k]))
        
        for k, new_val in keys_to_update:
            obj[k] = new_val

    update_recursive(data)

    with open(file_path, 'w', encoding='utf-8') as f:
        json.dump(data, f, indent=2, ensure_ascii=False)
    print("Updated es.json successfully.")

